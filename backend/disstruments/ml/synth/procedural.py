"""Procedural MIDI (PRD A2): licence-clean arrangements we generate and own.

Every Lakh-MIDI render is research-only because the compositions aren't cleared. This
module writes multi-track songs from scratch (seeded, deterministic): a drum kit groove,
a bass line, a chord part (block / arpeggio / strum), a lead melody and sometimes a pad or
horn line, over common pop/rock progressions. Programs are spread over every GM family the
renderer maps (`midi.ROLE_OF_PROGRAM`), so `LeafBalancer` can reach every leaf.

Layout `<root>/<group>/<song>.mid` matches `midi.composition_key`, so splits are by group
(the "artist" of procedural songs). `<root>/MIDI_LICENSE.json` marks the folder clean for
`build`. This is musically simple on purpose: the experiment is how much the real-music
gap widens when arrangements come from code instead of real songs (the licence cost).

    python -m disstruments.ml.synth procedural --out ~/datasets/procedural_midi --n-songs 3000
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from .midi import CYMBAL_NOTES, KIT_NOTES

LICENSE = {"commercial_clean": True,
           "license": "procedural (generated by disstruments.ml.synth.procedural; owned, no third-party compositions)"}

# Common progressions as scale degrees (0-based, major key); minor keys use the relative minor.
PROGRESSIONS = [[0, 4, 5, 3], [0, 5, 3, 4], [0, 3, 4, 4], [5, 3, 0, 4], [0, 3, 0, 4],
                [0, 4, 5, 2, 3, 0, 3, 4], [1, 4, 0, 0], [0, 6, 5, 4], [0, 0, 3, 4], [3, 4, 0, 5]]
MAJOR = [0, 2, 4, 5, 7, 9, 11]
# GM program pools per role (0-based), mixing programs that pin a leaf and generic ones.
PROGRAMS = {
    "chords": [0, 1, 2, 4, 5, 16, 17, 18, 24, 25, 26, 27, 29, 30, 88, 89, 90, 91, 94],
    "bass": [32, 33, 34, 35, 36, 37, 38, 39],
    "lead": [0, 4, 24, 26, 29, 56, 57, 64, 65, 66, 80, 81, 82, 84, 85, 87],
    "pad": [16, 19, 48, 88, 89, 90, 91, 92, 94, 95],
    "horn": [56, 57, 60, 61, 64, 65, 66, 67],
}
KICK, SNARE, CLOSED_HAT, OPEN_HAT, RIDE, CRASH, LOW_TOM, MID_TOM, HI_TOM = 36, 38, 42, 46, 51, 49, 45, 47, 50
assert {KICK, SNARE, CLOSED_HAT, OPEN_HAT, RIDE, CRASH, LOW_TOM, MID_TOM, HI_TOM} <= KIT_NOTES


def _chord(root_deg: int, key: int, minor: bool, octave: int, n: int = 3) -> list[int]:
    off = 5 if minor else 0                          # relative minor = degree 5 of major
    degs = [(root_deg + off + 2 * k) % 7 for k in range(n)]
    base = key + 12 * octave
    out, prev = [], -1
    for d in degs:
        p = base + MAJOR[d] + (12 if MAJOR[d] + base <= prev else 0)
        if out and p <= out[-1]:
            p += 12
        out.append(p); prev = p
    return out


def _drums(inst, rng, bars: int, beat: float, style: str) -> None:
    import pretty_midi as pm
    hat = RIDE if rng.random() < 0.2 else CLOSED_HAT
    sub = 4 if rng.random() < 0.3 else 2              # 16ths or 8ths on the hats
    for b in range(bars):
        t0 = b * 4 * beat
        if b % 8 == 0 and rng.random() < 0.7:
            inst.notes.append(pm.Note(int(rng.integers(90, 120)), CRASH, t0, t0 + beat))
        for k in range(4 * sub):
            t = t0 + k * beat / sub
            v = int(rng.integers(55, 95)) + (15 if k % sub == 0 else 0)
            note = OPEN_HAT if (k == 4 * sub - 1 and rng.random() < 0.3) else hat
            inst.notes.append(pm.Note(min(v, 127), note, t, t + beat / sub * 0.9))
        kicks = [0, 2] if style == "straight" else [0, 1.5, 2.5] if style == "syncopated" else [0, 1, 2, 3]
        for q in kicks:
            inst.notes.append(pm.Note(int(rng.integers(90, 120)), KICK, t0 + q * beat, t0 + (q + 0.5) * beat))
        for q in (1, 3):
            inst.notes.append(pm.Note(int(rng.integers(85, 115)), SNARE, t0 + q * beat, t0 + (q + 0.5) * beat))
        if b % 4 == 3 and rng.random() < 0.5:        # fill on the last beat
            for k, tom in enumerate([HI_TOM, MID_TOM, LOW_TOM, LOW_TOM]):
                t = t0 + 3 * beat + k * beat / 4
                inst.notes.append(pm.Note(int(rng.integers(80, 110)), tom, t, t + beat / 4))


def _bass(inst, rng, prog_degs, key, minor, bars, beat) -> None:
    import pretty_midi as pm
    pattern = rng.choice(["roots", "root_fifth", "eighths", "walk"])
    for b in range(bars):
        r = _chord(prog_degs[b % len(prog_degs)], key, minor, 2)[0]
        t0 = b * 4 * beat
        if pattern == "roots":
            steps = [(0, r, 2), (2, r, 2)]
        elif pattern == "root_fifth":
            steps = [(0, r, 1.5), (1.5, r + 7, 0.5), (2, r, 1), (3, r + 12 if rng.random() < .5 else r + 7, 1)]
        elif pattern == "eighths":
            steps = [(k / 2, r, 0.45) for k in range(8)]
        else:
            nxt = _chord(prog_degs[(b + 1) % len(prog_degs)], key, minor, 2)[0]
            steps = [(0, r, 1), (1, r + 4 if not minor else r + 3, 1), (2, r + 7, 1), (3, nxt - 1, 1)]
        for q, p, d in steps:
            inst.notes.append(pm.Note(int(rng.integers(80, 110)), int(p), t0 + q * beat, t0 + (q + d) * beat * 0.95))


def _chords(inst, rng, prog_degs, key, minor, bars, beat, octave=4) -> None:
    import pretty_midi as pm
    style = rng.choice(["block", "arpeggio", "strum", "offbeat"])
    for b in range(bars):
        ch = _chord(prog_degs[b % len(prog_degs)], key, minor, octave, n=int(rng.choice([3, 4])))
        t0 = b * 4 * beat
        if style == "block":
            hits = [(0, 2), (2, 2)]
            for q, d in hits:
                for p in ch:
                    inst.notes.append(pm.Note(int(rng.integers(60, 95)), p, t0 + q * beat, t0 + (q + d) * beat * 0.95))
        elif style == "arpeggio":
            seq = ch + ch[-2:0:-1]
            for k in range(8):
                p = seq[k % len(seq)]
                inst.notes.append(pm.Note(int(rng.integers(60, 95)), p, t0 + k * beat / 2, t0 + (k + 1) * beat / 2))
        elif style == "strum":
            for q in [0, 1, 1.5, 2.5, 3]:
                for k, p in enumerate(ch):
                    s = t0 + q * beat + k * 0.012
                    inst.notes.append(pm.Note(int(rng.integers(60, 100)), p, s, t0 + (q + 0.5) * beat))
        else:
            for q in [0.5, 1.5, 2.5, 3.5]:
                for p in ch:
                    inst.notes.append(pm.Note(int(rng.integers(60, 95)), p, t0 + q * beat, t0 + (q + 0.4) * beat))


def _melody(inst, rng, prog_degs, key, minor, bars, beat, octave=5) -> None:
    import pretty_midi as pm
    scale = [key + 12 * octave + MAJOR[(d + (5 if minor else 0)) % 7] + 12 * ((d + (5 if minor else 0)) // 7)
             for d in range(10)]
    pos = int(rng.integers(2, 7))
    for b in range(bars):
        t, end = b * 4 * beat, (b + 1) * 4 * beat
        if b % 4 == 3 and rng.random() < 0.4:        # breathe at phrase ends
            continue
        tones = {s for s in _chord(prog_degs[b % len(prog_degs)], key, minor, octave)}
        while t < end - 1e-6:
            d = float(rng.choice([0.5, 0.5, 1, 1, 1.5, 2])) * beat
            pos = int(np.clip(pos + rng.choice([-2, -1, -1, 0, 1, 1, 2]), 0, len(scale) - 1))
            p = scale[pos]
            if t == b * 4 * beat and tones:           # land on a chord tone on the downbeat
                p = min(tones, key=lambda c: abs(c - p))
            inst.notes.append(pm.Note(int(rng.integers(70, 110)), int(p), t, min(end, t + d) - 0.01))
            t += d


def song(seed: int) -> "object":
    """One procedural song (pretty_midi.PrettyMIDI), deterministic in `seed`."""
    import pretty_midi as pm
    rng = np.random.default_rng(seed)
    tempo = float(rng.integers(72, 165))
    beat = 60.0 / tempo
    key, minor = int(rng.integers(0, 12)), bool(rng.random() < 0.4)
    prog = PROGRESSIONS[int(rng.integers(len(PROGRESSIONS)))]
    bars = int(np.ceil(36.0 / (4 * beat)))           # >= 36 s: several 10 s windows
    m = pm.PrettyMIDI(initial_tempo=tempo)
    if rng.random() < 0.9:
        d = pm.Instrument(program=0, is_drum=True, name="drums")
        _drums(d, rng, bars, beat, str(rng.choice(["straight", "syncopated", "four"])))
        m.instruments.append(d)
    parts = [("bass", _bass), ("chords", _chords), ("lead", _melody)]
    if rng.random() < 0.5:
        parts.append(("pad", _chords))
    if rng.random() < 0.3:
        parts.append(("horn", _melody))
    for role, fn in parts:
        if role != "bass" and rng.random() < 0.15:   # vary the line-up
            continue
        inst = pm.Instrument(program=int(rng.choice(PROGRAMS[role])), name=role)
        kw = {"octave": 3} if role == "pad" else {"octave": 4} if role == "horn" else {}
        fn(inst, rng, prog, key, minor, bars, beat, **kw)
        m.instruments.append(inst)
    return m


def generate(out: Path, n_songs: int, seed: int = 0, songs_per_group: int = 10) -> Path:
    """Write `n_songs` songs as `<out>/g<k>/s<i>.mid` plus the licence marker."""
    out.mkdir(parents=True, exist_ok=True)
    for i in range(n_songs):
        g = out / f"g{i // songs_per_group:04d}"
        g.mkdir(exist_ok=True)
        song(seed * 1_000_003 + i).write(str(g / f"s{i:05d}.mid"))
    (out / "MIDI_LICENSE.json").write_text(json.dumps(LICENSE | {"seed": seed, "n_songs": n_songs}, indent=1))
    return out


def midi_licence(midi_root: Path) -> tuple[bool, str]:
    """(commercial_clean, licence text) for a MIDI root; Lakh (no marker) is never clean."""
    f = Path(midi_root) / "MIDI_LICENSE.json"
    if f.exists():
        d = json.loads(f.read_text())
        return bool(d.get("commercial_clean")), str(d.get("license", ""))
    return False, "CC-BY-4.0 (Lakh MIDI compilation; compositions not cleared)"


